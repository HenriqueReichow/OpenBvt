"""Display of the u16 sonar image (docs/DISPLAY.md): colormaps, thresholds,
gamma and auto intensity. No Qt here, so it can be used and tested on its own.

    m = ColorMapper(colormap("Copper"))          # gamma 0.5, auto intensity on (defaults)
    rgba = m.map(img)                            # (rows, cols, 4) uint8; value 0 = transparent
"""
import glob
import os

import numpy as np

N_COLORS = 4096
INTENSITY_RANGE = (1000, 65535)        # Intensity slider; top threshold = sum − intensity
SENSITIVITY_RANGE = (1, 999)           # Sensitivity slider = bottom threshold
DEFAULTS = dict(colormap="Copper", gamma=0.5, auto=True, sensitivity=20, intensity=10000)


# ---------------------------------------------------------------- colormaps

def _ramp(*knots):
    """Piecewise-linear RGB colormap from (position 0..1, r, g, b) knots → (N_COLORS, 3) uint8."""
    x = np.linspace(0.0, 1.0, N_COLORS)
    pos = [k[0] for k in knots]
    rgb = [np.interp(x, pos, [k[c] for k in knots]) for c in (1, 2, 3)]
    return (np.clip(np.stack(rgb, 1), 0, 1) * 255 + 0.5).astype(np.uint8)


def _copper():
    x = np.linspace(0.0, 1.0, N_COLORS)
    rgb = np.stack([np.minimum(1.25 * x, 1.0), 0.7812 * x, 0.4975 * x], 1)
    return (rgb * 255 + 0.5).astype(np.uint8)


def _viridis():
    """Polynomial fit of viridis (degree 6 per channel, public-domain coefficients)."""
    c = np.array([[0.2777273272234177, 0.005407344544966578, 0.3340998053353061],
                  [0.1050930431085774, 1.404613529898575, 1.384590162594685],
                  [-0.3308618287255563, 0.214847559468213, 0.09509516302823659],
                  [-4.634230498983486, -5.799100973351585, -19.33244095627987],
                  [6.228269936347081, 14.17993336680509, 56.69055260068105],
                  [4.776384997670288, -13.74514537774601, -65.35303263337234],
                  [-5.435455855934631, 4.645852612178535, 26.3124352495832]])
    x = np.linspace(0.0, 1.0, N_COLORS)[:, None]
    rgb = sum(c[k] * x ** k for k in range(7))
    return (np.clip(rgb, 0, 1) * 255 + 0.5).astype(np.uint8)


# our own colormaps, generated by formula ; Copper is the default
BUILTIN = {
    "Copper": _copper,
    "Grayscale": lambda: _ramp((0, 0, 0, 0), (1, 1, 1, 1)),
    "Jet": lambda: _ramp((0, 0, 0, 0.5), (0.125, 0, 0, 1), (0.375, 0, 1, 1), (0.625, 1, 1, 0),
                         (0.875, 1, 0, 0), (1, 0.5, 0, 0)),
    "Viridis": _viridis,
}


def load_cmap(path):
    """.cmap file (no header, blue-green-red triples) → (N, 3) uint8 RGB."""
    raw = np.fromfile(path, np.uint8)
    if raw.size == 0 or raw.size % 3:
        raise ValueError(f"{path}: not a .cmap file (size {raw.size} is not a multiple of 3)")
    return raw.reshape(-1, 3)[:, ::-1].copy()


def colormaps(folders=()):
    """{name: loader}: the built-in maps plus every *.cmap in `folders` (a .cmap replaces the built-in
    map with the same name, so existing .cmap files can be reused)."""
    out = dict(BUILTIN)
    for d in folders:
        for f in sorted(glob.glob(os.path.join(d, "*.cmap"))):
            name = os.path.splitext(os.path.basename(f))[0].capitalize()
            out[name] = (lambda f=f: load_cmap(f))
    return out


def colormap(name, folders=()):
    maps = colormaps(folders)
    if name not in maps:
        raise KeyError(f"unknown colormap {name!r} (available: {', '.join(maps)})")
    return maps[name]()


# ---------------------------------------------------------------- mapping

class ColorMapper:
    """u16 → RGBA through a 65536-entry table built from the thresholds, the gamma and the colormap.

    value 0                 → transparent (no data)
    1 … bottom−1            → first colour
    bottom … top            → colour round(((v − bottom)/(top − bottom))^gamma · (N − 1))
    above top               → last colour
    Auto mode: per image, bottom/top go to the 0.01 % / 99.99 % points of the histogram of the non-zero
    pixels (4096 bins), moving 1/5 of the way per image after the first one; top ≥ AUTO_TOP_MIN.
    """
    AUTO_TOP_MIN = INTENSITY_RANGE[0]

    def __init__(self, colors=None, gamma=DEFAULTS["gamma"], auto=DEFAULTS["auto"],
                 sensitivity=DEFAULTS["sensitivity"], intensity=DEFAULTS["intensity"]):
        self.colors = _copper() if colors is None else np.asarray(colors, np.uint8)
        self.gamma = float(gamma)
        self.bottom = int(sensitivity)
        self.top = self.top_for(intensity)
        self.auto = bool(auto)
        self._first_auto = True
        self._lut = None

    # sliders
    @staticmethod
    def top_for(intensity):
        return int(sum(INTENSITY_RANGE) - int(intensity))

    @property
    def intensity(self):
        return int(sum(INTENSITY_RANGE) - self.top)

    @property
    def sensitivity(self):
        return self.bottom

    def set_manual(self, sensitivity=None, intensity=None, gamma=None):
        if sensitivity is not None:
            self.bottom = int(np.clip(sensitivity, *SENSITIVITY_RANGE))
        if intensity is not None:
            self.top = self.top_for(np.clip(intensity, *INTENSITY_RANGE))
        if gamma is not None:
            self.gamma = float(gamma)
        self._lut = None

    def set_colors(self, colors):
        self.colors = np.asarray(colors, np.uint8)
        self._lut = None

    def set_auto(self, on):
        if on and not self.auto:
            self._first_auto = True
        self.auto = bool(on)

    # table
    def lut(self):
        if self._lut is None:
            n = len(self.colors)
            rgba = np.concatenate([self.colors, np.full((n, 1), 255, np.uint8)], 1)
            v = np.arange(65536)
            b, t = self.bottom, self.top
            if b < t:
                f = np.clip((v - b) / float(t - b), 0.0, 1.0) ** self.gamma
                idx = np.rint(f * (n - 1)).astype(np.int64)
            else:
                idx = np.full(65536, n // 2)
            lut = rgba[idx]
            lut[v < b] = rgba[0]
            lut[0] = 0
            self._lut = lut
        return self._lut

    def _auto_update(self, img):
        nz = img[img > 0]
        if nz.size == 0:
            return
        hist = np.bincount(nz >> 4, minlength=4096)
        c = np.cumsum(hist)
        tail = nz.size // 10000
        low = int(np.searchsorted(c, tail, side="left")) - 1           # last bin still under 0.01 %
        high = int(np.searchsorted(c, nz.size - tail, side="left"))    # first bin reaching 99.99 %
        low, high = min(max(low, 0) * 16, 65535), min(high * 16, 65535)
        if self._first_auto:
            b, t = low, high
            self._first_auto = False
        else:
            b = self.bottom + int((low - self.bottom) / 5)
            t = self.top + int((high - self.top) / 5)
        t, b = max(t, self.AUTO_TOP_MIN), max(b, 1)
        if (b, t) != (self.bottom, self.top):
            self.bottom, self.top = b, t
            self._lut = None

    def map(self, img):
        """u16 image → (rows, cols, 4) uint8 RGBA."""
        if self.auto:
            self._auto_update(img)
        return self.lut()[img]


# ---------------------------------------------------------------- geometry of the published XY image

def fan_extent(meta_image):
    """(x_min, x_max, y_min, y_max) in metres of a published XY image (docs/SERVER.md §3)."""
    res = meta_image["res"]
    x0 = -meta_image["origin_col"] * res
    y1 = meta_image["origin_row"] * res
    return x0, x0 + meta_image["cols"] * res, y1 - meta_image["rows"] * res, y1


def crop_fan(img, meta_image, radius):
    """Crops the XY image to the pixels within `radius` m of the sonar (the full image covers the
    head's maximum range). Returns (image, meta) with the origin moved accordingly."""
    res, r0, c0 = meta_image["res"], meta_image["origin_row"], meta_image["origin_col"]
    k = int(np.ceil(radius / res)) + 1
    top, bottom = max(r0 - k, 0), min(r0 + k + 1, img.shape[0])
    left, right = max(c0 - k, 0), min(c0 + k + 1, img.shape[1])
    out = img[top:bottom, left:right]
    return out, dict(meta_image, rows=out.shape[0], cols=out.shape[1], origin_row=r0 - top, origin_col=c0 - left)
